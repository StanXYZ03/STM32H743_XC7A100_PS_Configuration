# 简化的主键盘布局 (不含小键盘，便于显示)
KEYBOARD_ROWS = [ROW_0, ROW_1, ROW_2, ROW_3, ROW_4, ROW_5]

# HID -> (row_idx, col_idx) 映射
def build_hid_to_pos():
    m = {}
    for ri, row in enumerate(KEYBOARD_ROWS):
        col = 0
        for hid, w, _ in row:
            m[hid] = (ri, col)
            col += w
    return m

HID_TO_POS = build_hid_to_pos()
